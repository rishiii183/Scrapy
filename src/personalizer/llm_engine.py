"""
LLM Adapter Engine with Multi-Provider Support and Deterministic Fallback.

Supports:
- OpenAI, Google Gemini, and Anthropic Claude REST endpoints
- Pydantic schema validation for structured JSON generation
- Robust JSON block extraction (handles markdown ```json fences)
- Strict invariant validation on LLM output
- Transparent, automatic failover to TemplateEngine on missing keys,
  API timeouts, rate limits, malformed JSON, or invariant breaches
"""

import json
import logging
import os
import re
from typing import Any, Dict, Optional
import httpx
from pydantic import BaseModel, Field

from src.personalizer.prompts import (
    SYSTEM_PROMPT_PERSONALIZER,
    USER_PROMPT_TEMPLATE,
)
from src.personalizer.template_engine import (
    TemplateEngine,
    assert_zero_placeholders,
)

logger = logging.getLogger(__name__)


class GeneratedOutreachContent(BaseModel):
    """
    Validated outreach package generated by LLM or deterministic fallback.
    """
    icebreaker: str = Field(..., description="2-sentence personalized opening hook")
    offer_angle: str = Field(..., description="Revenue pain point angle")
    staged_email_subject: str = Field(..., description="Cold email subject line")
    staged_email_body: str = Field(..., description="Full cold email body copy")
    staged_whatsapp_msg: str = Field(..., description="Mobile WhatsApp message copy")


def extract_json_payload(raw_text: str) -> Dict[str, Any]:
    """
    Extract and parse JSON object from raw LLM text response.
    Handles markdown code blocks (```json ... ```) and leading/trailing chatter.
    """
    cleaned = raw_text.strip()

    # Pattern 1: Markdown code fence
    fence_match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", cleaned, re.DOTALL)
    if fence_match:
        return json.loads(fence_match.group(1))

    # Pattern 2: First { to last }
    brace_match = re.search(r"(\{.*\})", cleaned, re.DOTALL)
    if brace_match:
        return json.loads(brace_match.group(1))

    # Pattern 3: Direct parse
    return json.loads(cleaned)


def validate_icebreaker_invariants(icebreaker: str, city: str, specialty: str) -> None:
    """
    Verify icebreaker strictly satisfies all Milestone 3 acceptance criteria.
    Raises ValueError if any invariant is violated.
    """
    assert_zero_placeholders(icebreaker)

    # 1. Exactly 2 sentences ending with period
    sentences = [s.strip() for s in icebreaker.split(".") if s.strip()]
    if len(sentences) != 2:
        raise ValueError(
            f"Icebreaker must contain exactly 2 sentences, got {len(sentences)}: '{icebreaker}'"
        )

    # 2. City reference
    if city and city.lower() not in icebreaker.lower():
        raise ValueError(f"Icebreaker missing exact city '{city}': '{icebreaker}'")

    # 3. Specialty reference
    spec_clean = specialty.lower().replace("&", "and")
    ice_lower = icebreaker.lower().replace("&", "and")
    # Check if specialty keywords appear
    spec_keywords = [w for w in spec_clean.split() if len(w) > 3 and w not in {"roofing", "contractors"}]
    if not any(k in ice_lower for k in spec_keywords) and "roofing" not in ice_lower:
        raise ValueError(f"Icebreaker missing trade specialty '{specialty}': '{icebreaker}'")

    # 4. Competitor & Google Maps & emergency repairs & revenue loss
    if "google maps" not in ice_lower:
        raise ValueError(f"Icebreaker must mention Google Maps: '{icebreaker}'")

    if not ("competitor" in ice_lower or "competitors" in ice_lower):
        raise ValueError(f"Icebreaker must mention competitors: '{icebreaker}'")

    if "emergency" not in ice_lower and "roof repairs" not in ice_lower:
        raise ValueError(f"Icebreaker must mention emergency roof repairs: '{icebreaker}'")

    if not any(term in ice_lower for term in ["lost", "missing out", "losing", "siphoning", "capturing", "lose", "loss"]):
        raise ValueError(f"Icebreaker must highlight revenue loss: '{icebreaker}'")


class LLMEngine:
    """
    Outreach generation engine with LLM provider adapters and guaranteed deterministic fallback.
    """

    def __init__(
        self,
        template_engine: Optional[TemplateEngine] = None,
        provider: Optional[str] = None,
        model: Optional[str] = None,
        api_key: Optional[str] = None,
        timeout: float = 10.0,
    ) -> None:
        self.template_engine = template_engine or TemplateEngine()
        self.timeout = timeout
        self.api_key = api_key
        self.provider = provider
        self.model = model

        # Auto-detect provider and key if not explicitly given
        if not self.api_key:
            if os.getenv("OPENAI_API_KEY"):
                self.provider = self.provider or "openai"
                self.api_key = os.getenv("OPENAI_API_KEY")
                self.model = self.model or "gpt-4o-mini"
            elif os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY"):
                self.provider = self.provider or "gemini"
                self.api_key = os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")
                self.model = self.model or "gemini-1.5-flash"
            elif os.getenv("ANTHROPIC_API_KEY"):
                self.provider = self.provider or "anthropic"
                self.api_key = os.getenv("ANTHROPIC_API_KEY")
                self.model = self.model or "claude-3-haiku-20240307"

    @property
    def is_available(self) -> bool:
        """True if an external LLM API key and provider are configured."""
        return bool(self.api_key and self.provider)

    def _call_openai(self, prompt: str) -> str:
        """Call OpenAI chat completions API."""
        url = "https://api.openai.com/v1/chat/completions"
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self.model or "gpt-4o-mini",
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT_PERSONALIZER},
                {"role": "user", "content": prompt},
            ],
            "response_format": {"type": "json_object"},
            "temperature": 0.4,
        }
        with httpx.Client(timeout=self.timeout) as client:
            resp = client.post(url, headers=headers, json=payload)
            resp.raise_for_status()
            data = resp.json()
            return data["choices"][0]["message"]["content"]

    def _call_gemini(self, prompt: str) -> str:
        """Call Google Gemini generateContent REST API."""
        model_name = self.model or "gemini-1.5-flash"
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent?key={self.api_key}"
        headers = {"Content-Type": "application/json"}
        payload = {
            "contents": [{
                "parts": [
                    {"text": SYSTEM_PROMPT_PERSONALIZER + "\n\n" + prompt}
                ]
            }],
            "generationConfig": {
                "response_mime_type": "application/json",
                "temperature": 0.4,
            }
        }
        with httpx.Client(timeout=self.timeout) as client:
            resp = client.post(url, headers=headers, json=payload)
            resp.raise_for_status()
            data = resp.json()
            return data["candidates"][0]["content"]["parts"][0]["text"]

    def _call_anthropic(self, prompt: str) -> str:
        """Call Anthropic messages API."""
        url = "https://api.anthropic.com/v1/messages"
        headers = {
            "x-api-key": self.api_key or "",
            "anthropic-version": "2023-06-01",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self.model or "claude-3-haiku-20240307",
            "max_tokens": 1000,
            "system": SYSTEM_PROMPT_PERSONALIZER,
            "messages": [
                {"role": "user", "content": prompt}
            ],
            "temperature": 0.4,
        }
        with httpx.Client(timeout=self.timeout) as client:
            resp = client.post(url, headers=headers, json=payload)
            resp.raise_for_status()
            data = resp.json()
            return data["content"][0]["text"]

    def _call_provider(self, prompt: str) -> str:
        """Dispatch call to active provider."""
        if self.provider == "openai":
            return self._call_openai(prompt)
        elif self.provider == "gemini":
            return self._call_gemini(prompt)
        elif self.provider == "anthropic":
            return self._call_anthropic(prompt)
        raise ValueError(f"Unsupported LLM provider: {self.provider}")

    def generate(self, context: Dict[str, Any], template_index: Optional[int] = None) -> GeneratedOutreachContent:
        """
        Generate outreach content. Attempts LLM call if configured;
        automatically falls back to TemplateEngine on any error or if offline.
        """
        city = (context.get("city") or "").strip()
        specialty = (context.get("specialty") or context.get("industry_niche") or "").strip()

        if self.is_available:
            try:
                # Render user prompt
                prompt = self.template_engine.jinja_env.from_string(USER_PROMPT_TEMPLATE).render(**context)
                raw_response = self._call_provider(prompt)
                parsed = extract_json_payload(raw_response)
                content = GeneratedOutreachContent.model_validate(parsed)

                # Validate strict invariants
                validate_icebreaker_invariants(content.icebreaker, city, specialty)
                assert_zero_placeholders(content.staged_email_subject)
                assert_zero_placeholders(content.staged_email_body)
                assert_zero_placeholders(content.staged_whatsapp_msg)

                return content
            except Exception as e:
                logger.warning("LLM generation failed (%s: %s). Falling back to TemplateEngine.", type(e).__name__, e)

        # Deterministic Jinja2 Fallback
        fallback_data = self.template_engine.render_all(context, template_index=template_index)
        return GeneratedOutreachContent.model_validate(fallback_data)
